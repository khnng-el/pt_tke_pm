-- =====================================================
-- Unified setup script for the hotel booking project
-- Default database name matches config.py: hotel_management
-- =====================================================

CREATE DATABASE IF NOT EXISTS `hotel_management`
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE `hotel_management`;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS `notifications`;
DROP TABLE IF EXISTS `checkout_invoices`;
DROP TABLE IF EXISTS `checkin_records`;
DROP TABLE IF EXISTS `payment`;
DROP TABLE IF EXISTS `reviews`;
DROP TABLE IF EXISTS `room_images`;
DROP TABLE IF EXISTS `hotel_images`;
DROP TABLE IF EXISTS `services`;
DROP TABLE IF EXISTS `bookings`;
DROP TABLE IF EXISTS `hotel_locations`;
DROP TABLE IF EXISTS `rooms`;
DROP TABLE IF EXISTS `hotels`;
DROP TABLE IF EXISTS `user_security`;
DROP TABLE IF EXISTS `users`;

CREATE TABLE `users` (
  `user_id` int NOT NULL AUTO_INCREMENT,
  `username` varchar(50) NOT NULL,
  `password` varchar(255) NOT NULL,
  `email` varchar(100) NOT NULL,
  `full_name` varchar(100) DEFAULT NULL,
  `phone` varchar(20) DEFAULT NULL,
  `role` ENUM('ADMIN', 'OWNER', 'CUSTOMER') NOT NULL DEFAULT 'CUSTOMER',
  `is_active` tinyint(1) NOT NULL DEFAULT 1,
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`user_id`),
  UNIQUE KEY `uq_users_username` (`username`),
  UNIQUE KEY `uq_users_email` (`email`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `user_security` (
  `user_id` int NOT NULL,
  `email_verified` tinyint(1) NOT NULL DEFAULT 0,
  `email_verification_token` varchar(100) DEFAULT NULL,
  `password_reset_token` varchar(100) DEFAULT NULL,
  `password_reset_expires` datetime DEFAULT NULL,
  `last_login` datetime DEFAULT NULL,
  `login_attempts` int NOT NULL DEFAULT 0,
  `locked_until` datetime DEFAULT NULL,
  PRIMARY KEY (`user_id`),
  CONSTRAINT `fk_user_security_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `hotels` (
  `hotel_id` int NOT NULL AUTO_INCREMENT,
  `hotel_name` varchar(50) NOT NULL,
  `address_hotel` varchar(150) NOT NULL,
  `tel` varchar(20) NOT NULL,
  `rating` float DEFAULT NULL,
  `descriptions` varchar(1000) DEFAULT NULL,
  `owner_id` int NOT NULL,
  PRIMARY KEY (`hotel_id`),
  KEY `idx_hotels_owner_id` (`owner_id`),
  CONSTRAINT `fk_hotels_owner`
    FOREIGN KEY (`owner_id`) REFERENCES `users` (`user_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `hotel_locations` (
  `hotel_id` int NOT NULL,
  `latitude` float DEFAULT NULL,
  `longitude` float DEFAULT NULL,
  PRIMARY KEY (`hotel_id`),
  CONSTRAINT `fk_hotel_locations_hotel`
    FOREIGN KEY (`hotel_id`) REFERENCES `hotels` (`hotel_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `rooms` (
  `room_id` int NOT NULL AUTO_INCREMENT,
  `room_type` varchar(35) NOT NULL,
  `availableRooms` int DEFAULT 0,
  `price` bigint NOT NULL,
  `hotel_id` int NOT NULL,
  PRIMARY KEY (`room_id`),
  KEY `idx_rooms_hotel_id` (`hotel_id`),
  CONSTRAINT `fk_rooms_hotel`
    FOREIGN KEY (`hotel_id`) REFERENCES `hotels` (`hotel_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `services` (
  `id_service` int NOT NULL AUTO_INCREMENT,
  `serviceName` varchar(255) NOT NULL,
  `room_id` int NOT NULL,
  PRIMARY KEY (`id_service`),
  KEY `idx_services_room_id` (`room_id`),
  CONSTRAINT `fk_services_room`
    FOREIGN KEY (`room_id`) REFERENCES `rooms` (`room_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `hotel_images` (
  `image_id` int NOT NULL AUTO_INCREMENT,
  `hotel_id` int NOT NULL,
  `image_path` varchar(255) NOT NULL,
  `is_main` tinyint(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (`image_id`),
  KEY `idx_hotel_images_hotel_id` (`hotel_id`),
  CONSTRAINT `fk_hotel_images_hotel`
    FOREIGN KEY (`hotel_id`) REFERENCES `hotels` (`hotel_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `room_images` (
  `image_id` int NOT NULL AUTO_INCREMENT,
  `room_id` int NOT NULL,
  `image_path` varchar(255) NOT NULL,
  `is_main` tinyint(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (`image_id`),
  KEY `idx_room_images_room_id` (`room_id`),
  CONSTRAINT `fk_room_images_room`
    FOREIGN KEY (`room_id`) REFERENCES `rooms` (`room_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `reviews` (
  `review_id` int NOT NULL AUTO_INCREMENT,
  `user_id` int NOT NULL,
  `rating` float DEFAULT NULL,
  `comment` varchar(200) DEFAULT NULL,
  `hotel_id` int NOT NULL,
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`review_id`),
  KEY `idx_reviews_user_id` (`user_id`),
  KEY `idx_reviews_hotel_id` (`hotel_id`),
  CONSTRAINT `fk_reviews_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_reviews_hotel`
    FOREIGN KEY (`hotel_id`) REFERENCES `hotels` (`hotel_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `bookings` (
  `booking_id` int NOT NULL AUTO_INCREMENT,
  `user_id` int NOT NULL,
  `room_id` int NOT NULL,
  `check_in` datetime NOT NULL,
  `check_out` datetime NOT NULL,
  `total_price` float NOT NULL,
  `num_rooms` int NOT NULL DEFAULT 1,
  `status` varchar(20) DEFAULT 'pending',
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`booking_id`),
  KEY `idx_bookings_user_id` (`user_id`),
  KEY `idx_bookings_room_id` (`room_id`),
  CONSTRAINT `fk_bookings_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_bookings_room`
    FOREIGN KEY (`room_id`) REFERENCES `rooms` (`room_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `payment` (
  `payment_id` int NOT NULL AUTO_INCREMENT,
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
  `booking_id` int DEFAULT NULL,
  `txn_ref` varchar(100) DEFAULT NULL,
  `amount` bigint DEFAULT NULL,
  `bank_code` varchar(50) DEFAULT NULL,
  `pay_date` datetime DEFAULT NULL,
  `response_code` varchar(10) DEFAULT NULL,
  `payment_status` varchar(50) DEFAULT NULL,
  `secure_hash` text,
  `payment_method` varchar(50) DEFAULT NULL,
  PRIMARY KEY (`payment_id`),
  KEY `idx_payment_booking_id` (`booking_id`),
  CONSTRAINT `fk_payment_booking`
    FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`booking_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `checkin_records` (
  `checkin_id` int NOT NULL AUTO_INCREMENT,
  `booking_id` int NOT NULL,
  `user_id` int NOT NULL,
  `owner_id` int NOT NULL,
  `hotel_id` int NOT NULL,
  `checkin_at` datetime NOT NULL,
  `note` text,
  `status` varchar(30) NOT NULL DEFAULT 'confirmed',
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `confirmed_at` datetime DEFAULT NULL,
  PRIMARY KEY (`checkin_id`),
  UNIQUE KEY `uq_checkin_records_booking_id` (`booking_id`),
  KEY `idx_checkin_records_user_id` (`user_id`),
  KEY `idx_checkin_records_owner_id` (`owner_id`),
  KEY `idx_checkin_records_hotel_id` (`hotel_id`),
  CONSTRAINT `fk_checkin_records_booking`
    FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`booking_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_checkin_records_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_checkin_records_owner`
    FOREIGN KEY (`owner_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_checkin_records_hotel`
    FOREIGN KEY (`hotel_id`) REFERENCES `hotels` (`hotel_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `checkout_invoices` (
  `checkout_id` int NOT NULL AUTO_INCREMENT,
  `booking_id` int NOT NULL,
  `user_id` int NOT NULL,
  `owner_id` int NOT NULL,
  `hotel_id` int NOT NULL,
  `amount` bigint NOT NULL DEFAULT 0,
  `note` text,
  `status` varchar(30) NOT NULL DEFAULT 'no_charge',
  `txn_ref` varchar(100) DEFAULT NULL,
  `bank_code` varchar(50) DEFAULT NULL,
  `pay_date` datetime DEFAULT NULL,
  `response_code` varchar(10) DEFAULT NULL,
  `secure_hash` text,
  `actual_checkout_at` datetime DEFAULT NULL,
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
  `updated_at` datetime DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  `sent_at` datetime DEFAULT NULL,
  PRIMARY KEY (`checkout_id`),
  UNIQUE KEY `uq_checkout_invoices_booking_id` (`booking_id`),
  KEY `idx_checkout_invoices_user_id` (`user_id`),
  KEY `idx_checkout_invoices_owner_id` (`owner_id`),
  KEY `idx_checkout_invoices_hotel_id` (`hotel_id`),
  CONSTRAINT `fk_checkout_invoices_booking`
    FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`booking_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_checkout_invoices_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_checkout_invoices_owner`
    FOREIGN KEY (`owner_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_checkout_invoices_hotel`
    FOREIGN KEY (`hotel_id`) REFERENCES `hotels` (`hotel_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `notifications` (
  `id` int NOT NULL AUTO_INCREMENT,
  `user_id` int NOT NULL,
  `type` varchar(50) DEFAULT NULL,
  `message` varchar(255) DEFAULT NULL,
  `read` tinyint(1) NOT NULL DEFAULT 0,
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_notifications_user_id` (`user_id`),
  CONSTRAINT `fk_notifications_user`
    FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

